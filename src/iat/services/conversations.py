"""Owner-scoped, resource-bounded conversation store.

Conversation ids are generated by the server, and every read or write is checked against the
verified caller identity. A conversation owned by someone else is indistinguishable from one
that does not exist (both raise ``NotFoundError``), so ids cannot be probed.

Resource bounds (INTENT-002 finding C), all configurable via ``ConversationLimits``:

* ``max_conversations`` — total stored conversations. At capacity, the least recently active
  conversation is evicted.
* ``max_conversations_per_owner`` — per caller. At capacity, that caller's least recently active
  conversation is evicted, so one caller cannot push everyone else out by itself.
* ``max_turns_per_conversation`` — a sliding window; the oldest turns are dropped and counted.
* ``max_message_chars`` — enforced by the runner before any work is done.
* ``idle_ttl_seconds`` — conversations idle longer than this are removed. Expired conversations
  behave exactly like ones that never existed (404).

Expiry is enforced on every operation (lazy purge, oldest first). The clock is injectable so the
bounds are tested deterministically. V1 keeps conversations in process memory;
``ConversationRepository`` is the seam for a durable store in a later progression.
"""

from __future__ import annotations

import datetime as dt
import logging
import threading
import time
import uuid
from collections import Counter, OrderedDict
from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any, Protocol

from iat.core.errors import NotFoundError
from iat.schemas.api import ConversationSummary, ConversationView, Turn
from iat.security.identity import Identity

logger = logging.getLogger("iat.conversations")


@dataclass(frozen=True)
class ConversationLimits:
    max_conversations: int = 1000
    max_conversations_per_owner: int = 50
    max_turns_per_conversation: int = 40
    max_message_chars: int = 2000
    idle_ttl_seconds: float = 3600.0

    def __post_init__(self) -> None:
        if min(self.max_conversations, self.max_conversations_per_owner) < 1:
            raise ValueError("Conversation capacity limits must be at least 1")
        if self.max_turns_per_conversation < 2:
            raise ValueError("max_turns_per_conversation must be at least 2 (one exchange)")
        if self.max_message_chars < 1 or self.idle_ttl_seconds <= 0:
            raise ValueError("Message size and idle TTL limits must be positive")


@dataclass
class _Conversation:
    conversation_id: str
    owner: str
    agent: str
    created_at: dt.datetime
    last_active: float
    turns: list[Turn] = field(default_factory=list)
    dropped_turns: int = 0


class ConversationRepository(Protocol):
    @property
    def limits(self) -> ConversationLimits: ...
    def create(self, identity: Identity, agent: str) -> str: ...
    def ensure(self, identity: Identity, conversation_id: str, agent: str) -> None: ...
    def get(self, identity: Identity, conversation_id: str) -> ConversationView: ...
    def list_for(self, identity: Identity) -> list[ConversationSummary]: ...
    def append(
        self, identity: Identity, conversation_id: str, agent: str, turns: list[Turn]
    ) -> None: ...


class InMemoryConversationRepository:
    def __init__(
        self,
        limits: ConversationLimits | None = None,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self._limits = limits or ConversationLimits()
        self._clock = clock
        # Ordered least- to most-recently active; the front is always the eviction candidate.
        self._items: OrderedDict[str, _Conversation] = OrderedDict()
        self._by_owner: dict[str, OrderedDict[str, None]] = {}
        self._lock = threading.Lock()
        self.evictions: Counter[str] = Counter()

    @property
    def limits(self) -> ConversationLimits:
        return self._limits

    def __len__(self) -> int:
        with self._lock:
            self._purge_expired(self._clock())
            return len(self._items)

    # --- internal bookkeeping (call with lock held) ---------------------------------------

    def _remove(self, conversation_id: str, reason: str) -> None:
        conv = self._items.pop(conversation_id)
        owned = self._by_owner[conv.owner]
        del owned[conversation_id]
        if not owned:
            del self._by_owner[conv.owner]
        self.evictions[reason] += 1
        logger.info("conversation_evicted", extra={"reason": reason})

    def _purge_expired(self, now: float) -> None:
        ttl = self._limits.idle_ttl_seconds
        while self._items:
            oldest_id, oldest = next(iter(self._items.items()))
            if now - oldest.last_active < ttl:
                break
            self._remove(oldest_id, "idle_expired")

    def _touch(self, conv: _Conversation, now: float) -> None:
        conv.last_active = now
        self._items.move_to_end(conv.conversation_id)
        self._by_owner[conv.owner].move_to_end(conv.conversation_id)

    def _owned(self, identity: Identity, conversation_id: str) -> _Conversation:
        conv = self._items.get(conversation_id)
        if conv is None or conv.owner != identity.subject:
            raise NotFoundError("Conversation not found")
        return conv

    # --- public API -------------------------------------------------------------------------

    def create(self, identity: Identity, agent: str) -> str:
        conversation_id = uuid.uuid4().hex
        with self._lock:
            now = self._clock()
            self._purge_expired(now)
            owned = self._by_owner.get(identity.subject)
            if owned is not None and len(owned) >= self._limits.max_conversations_per_owner:
                self._remove(next(iter(owned)), "owner_capacity")
            if len(self._items) >= self._limits.max_conversations:
                self._remove(next(iter(self._items)), "global_capacity")
            self._items[conversation_id] = _Conversation(
                conversation_id=conversation_id,
                owner=identity.subject,
                agent=agent,
                created_at=dt.datetime.now(dt.UTC),
                last_active=now,
            )
            self._by_owner.setdefault(identity.subject, OrderedDict())[conversation_id] = None
        return conversation_id

    def get(self, identity: Identity, conversation_id: str) -> ConversationView:
        with self._lock:
            self._purge_expired(self._clock())
            conv = self._owned(identity, conversation_id)
            return ConversationView(
                conversation_id=conv.conversation_id,
                agent=conv.agent,
                created_at=conv.created_at,
                turns=list(conv.turns),
                dropped_turns=conv.dropped_turns,
            )

    def list_for(self, identity: Identity) -> list[ConversationSummary]:
        with self._lock:
            self._purge_expired(self._clock())
            return [
                ConversationSummary(
                    conversation_id=c.conversation_id,
                    agent=c.agent,
                    created_at=c.created_at,
                    turn_count=len(c.turns),
                )
                for c in (self._items[cid] for cid in self._by_owner.get(identity.subject, {}))
            ]

    def append(
        self, identity: Identity, conversation_id: str, agent: str, turns: list[Turn]
    ) -> None:
        with self._lock:
            now = self._clock()
            self._purge_expired(now)
            conv = self._owned(identity, conversation_id)
            if conv.agent != agent:
                raise NotFoundError("Conversation not found for this agent")
            conv.turns.extend(turns)
            overflow = len(conv.turns) - self._limits.max_turns_per_conversation
            if overflow > 0:
                del conv.turns[:overflow]
                conv.dropped_turns += overflow
            self._touch(conv, now)

    def ensure(self, identity: Identity, conversation_id: str, agent: str) -> None:
        """Validate ownership and agent before running anything; refreshes idle time."""
        with self._lock:
            now = self._clock()
            self._purge_expired(now)
            conv = self._owned(identity, conversation_id)
            if conv.agent != agent:
                raise NotFoundError("Conversation not found for this agent")
            self._touch(conv, now)


def turn(role: str, content: str, **extra: Any) -> Turn:
    return Turn(role=role, content=content, at=dt.datetime.now(dt.UTC), **extra)
